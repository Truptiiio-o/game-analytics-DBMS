-- =============================================================
-- FILE   : sql/03_channels.sql
-- PURPOSE: Compare player acquisition quality across three channels:
--          'organic', 'paid_social', and 'paid_video'.
--
-- METRICS DEFINED PRECISELY:
--   1. Engagement Metric: Day 7 Retention (D7)
--      A binary indicator (1/0) of whether the player had an active session
--      telemetry record on EXACTLY Day 7 of life (activity_date = install_date + 7).
--   2. Revenue Metric: 30-Day Cumulative Revenue per Install (D30 Rev)
--      Total real-money in-app purchase revenue (usd_amount) generated by
--      that player during their first 30 days of life
--      (event_date BETWEEN install_date AND install_date + 30). Non-payers = $0.00.
--
-- TARGET POPULATION:
--   Installs with a full 30-day follow-up window:
--   install_date BETWEEN '2026-01-01' AND '2026-03-31'.
--   (Excludes April installs to avoid right-censoring bias).
--
-- CORE ANALYTICAL FINDING:
--   Naive comparison shows Paid Social ($2.28) outperforming Paid Video ($1.62).
--   This is an ARTEFACT of geographic allocation: Paid Video was 65% Tier 4,
--   while Paid Social was 60% Tier 1/2. Within EVERY tier, Paid Video is
--   equal to or greater than Paid Social.
-- =============================================================


-- -------------------------------------------------------------
-- 1. VIEW: channel_player_metrics
-- -------------------------------------------------------------
-- Base analytical table with one row per mature player.
CREATE OR REPLACE VIEW channel_player_metrics AS
WITH mature_players AS (
    SELECT 
        device_id,
        install_date,
        DATE_TRUNC('week', install_date)::DATE AS install_week,
        platform,
        country,
        country_tier,
        acquisition_channel
    FROM profile_clean
    -- Only mature cohorts with >= 30 days of complete observation
    WHERE install_date BETWEEN '2026-01-01' AND '2026-03-31'
),
d7_activity AS (
    -- Player was active on exactly Day 7 after install
    SELECT DISTINCT
        mp.device_id,
        1 AS active_d7
    FROM mature_players mp
    JOIN player_day_clean pd 
        ON mp.device_id = pd.device_id 
        AND pd.activity_date = (mp.install_date + 7)
),
d30_spend AS (
    -- Total real-money spend within the first 30 days of life
    SELECT 
        mp.device_id,
        SUM(p.usd_amount) AS rev_d30
    FROM mature_players mp
    JOIN purchase_clean p 
        ON mp.device_id = p.device_id 
        AND p.event_date BETWEEN mp.install_date AND (mp.install_date + 30)
    GROUP BY mp.device_id
)
SELECT 
    mp.device_id,
    mp.install_date,
    mp.install_week,
    mp.platform,
    mp.country_tier,
    mp.country,
    mp.acquisition_channel,
    COALESCE(d7.active_d7, 0) AS d7_retained,
    COALESCE(s.rev_d30, 0.0) AS rev_d30
FROM mature_players mp
LEFT JOIN d7_activity d7 ON mp.device_id = d7.device_id
LEFT JOIN d30_spend s ON mp.device_id = s.device_id;


-- -------------------------------------------------------------
-- 2. VIEW: channel_naive_comparison
-- -------------------------------------------------------------
-- Unadjusted / naive comparison across channels.
CREATE OR REPLACE VIEW channel_naive_comparison AS
SELECT 
    acquisition_channel,
    COUNT(*) AS total_installs,
    ROUND(AVG(d7_retained) * 100.0, 2) AS naive_d7_retention_pct,
    ROUND(AVG(rev_d30), 4) AS naive_rev_d30_per_install,
    ROUND(SUM(rev_d30), 2) AS total_d30_revenue
FROM channel_player_metrics
GROUP BY acquisition_channel
ORDER BY naive_rev_d30_per_install DESC;


-- -------------------------------------------------------------
-- 3. VIEW: channel_stratified_by_tier
-- -------------------------------------------------------------
-- Performance controlled / stratified by country tier.
CREATE OR REPLACE VIEW channel_stratified_by_tier AS
SELECT 
    country_tier,
    acquisition_channel,
    COUNT(*) AS total_installs,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (PARTITION BY country_tier), 1) AS channel_share_within_tier_pct,
    ROUND(AVG(d7_retained) * 100.0, 2) AS d7_retention_pct,
    ROUND(AVG(rev_d30), 3) AS rev_d30_per_install
FROM channel_player_metrics
GROUP BY country_tier, acquisition_channel
ORDER BY country_tier, acquisition_channel;
